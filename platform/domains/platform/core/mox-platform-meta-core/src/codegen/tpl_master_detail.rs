//! TPL-03 主子表模板：主实体 + 明细实体 → 双 DDL / 嵌套 Rust 模型 / API / 主子页面 / 路由 / 菜单。
//! 明细表自动携带 `master_id` 外键列。

use std::collections::BTreeMap;
